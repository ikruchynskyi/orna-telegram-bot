def list_guides() -> list:
    """(topic_key, title) pairs, for the /orna system prompt to advertise
    what's available - derived from GUIDES itself so the prompt can't
    silently drift out of sync with what's actually on disk."""
    return [(key, g["title"]) for key, g in GUIDES.items()]


def resolve_guide(name: str) -> Optional[str]:
    """Resolve a free-text class/build/topic name to a GUIDES key -
    exact/substring match against the key and its aliases first, then a
    difflib fallback for typos (same two-step pattern orna_knowledge.py's
    _fuzzy_correct and orna_aussies.py's _resolve_stat_field already use
    elsewhere in this repo). None if nothing reasonably matches."""
    needle = name.strip().lower()
    if not needle:
        return None

    for key, g in GUIDES.items():
        if needle == key or needle in [a.lower() for a in g["aliases"]]:
            return key

    for key, g in GUIDES.items():
        candidates = [key] + g["aliases"]
        if any(needle in c or c in needle for c in (c.lower() for c in candidates)):
            return key

    alias_to_key = {a.lower(): key for key, g in GUIDES.items() for a in [key] + g["aliases"]}
    close = difflib.get_close_matches(needle, alias_to_key.keys(), n=1, cutoff=0.75)
    return alias_to_key[close[0]] if close else None


def read_guide(topic_key: str) -> Optional[str]:
    """Full raw file content for an already-resolved topic_key - no
    truncation here, that's the caller's job (how much context budget to
    spend is a loop-level decision, not this reader's)."""
    g = GUIDES.get(topic_key)
    if g is None:
        return None
    path = Path(__file__).with_name(g["path"])
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8")


def _demo() -> None:
    """Run via `python3 orna_guides.py`."""
    assert resolve_guide("thief") == "thief"
    assert resolve_guide("realmshifter") == "thief"
    assert resolve_guide("Realmshifter raiding") == "thief"
    assert resolve_guide("swashbuckler") == "swash"
    assert resolve_guide("towers of olympia") == "towers"
    assert resolve_guide("gilga") == "gilgamesh"
    assert resolve_guide("nonexistent-class-xyz-123") is None
    assert resolve_guide("") is None

    for key in GUIDES:
        content = read_guide(key)
        assert content, f"{key}: expected non-empty guide content"
        assert len(content) > 500, f"{key}: suspiciously short ({len(content)} chars)"

    print(f"orna_guides._demo: all checks passed ({len(GUIDES)} guides)")


if __name__ == "__main__":
    _demo()
