"""
orna_guides.py
================
Manifest + reader for the per-class/build/topic community guides
(orna_guide_<topic>.txt, generated by orna_scrape_guides.py - see that
script's docstring for sources). Deliberately NOT the same shape as
orna_knowledge.py: that module holds ONE flattened multi-section corpus,
fuzzy-searched as a single blob, because its content is short community-
wiki FACTS (tier/HP/resistance rows) where a matching line or two is a
complete answer. These guides are long-form REASONING - why a build
works, tradeoffs between two setups - where grepping a fragment out
would lose the argument around it, so the right unit to hand the model
is "the whole guide for the class this question is about", selected by
name, not searched piecemeal. That's what resolve_guide/read_guide are
for; the ReAct loop's own class_guide tool (telegram_orna.py) is the
only caller.
"""
